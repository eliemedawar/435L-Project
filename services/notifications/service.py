"""Business logic of the Notification and Alert Management Service. Owner: Elie Medawar."""
from common.clients import log_event
from common.db import db, utcnow
from common.enums import NOTIFICATION_STATUSES, NOTIFICATION_TYPES, SEVERITIES
from common.errors import ForbiddenError, NotFoundError, ValidationError
from common.roles import ADMIN, ANALYST, AUDITOR
from common.validators import clean_string, reject_unknown_fields, require_fields, validate_enum
from models.notifications import Notification
from models.users import User


class NotificationService:
    CREATE_FIELDS = ("user_id", "title", "message", "notification_type", "severity")
    SEARCH_PARAMS = ("user", "type", "severity", "status")

    # ---------- helpers ----------
    @staticmethod
    def get(notification_id):
        notification = db.session.get(Notification, notification_id)
        if notification is None:
            raise NotFoundError(f"Notification with id {notification_id} not found")
        return notification

    @staticmethod
    def _deny(actor, message, description):
        log_event(actor["user_id"], "UNAUTHORIZED_ACCESS", description, severity="Warning")
        raise ForbiddenError(message)

    @staticmethod
    def _sees_everything(actor):
        """Admins manage all notifications; auditors may read all of them. Others only their own."""
        return actor["role"] in (ADMIN, AUDITOR)

    @classmethod
    def _check_owner(cls, notification, actor, action):
        if not cls._sees_everything(actor) and notification.user_id != actor["user_id"]:
            cls._deny(actor, "You can only access your own notifications",
                      f"'{actor['username']}' tried to {action} notification {notification.id} of user "
                      f"{notification.user_id}")

    # ---------- operations ----------
    @staticmethod
    def create(data, actor):
        reject_unknown_fields(data, NotificationService.CREATE_FIELDS)
        require_fields(data, NotificationService.CREATE_FIELDS)
        user_id = data["user_id"]
        if isinstance(user_id, bool) or not isinstance(user_id, int):
            raise ValidationError("'user_id' must be an integer")
        if db.session.get(User, user_id) is None:
            raise ValidationError(f"User with id {user_id} does not exist")

        notification = Notification(
            user_id=user_id,
            title=clean_string(data, "title", 150),
            message=clean_string(data, "message", 1000),
            notification_type=validate_enum(data["notification_type"], NOTIFICATION_TYPES, "notification_type"),
            severity=validate_enum(data["severity"], SEVERITIES, "severity"),
        )
        db.session.add(notification)
        db.session.commit()
        if actor["role"] == ADMIN:   # notifications generated by other services are already logged there
            log_event(actor["user_id"], "NOTIFICATION_CREATED",
                      f"Notification {notification.id} ({notification.notification_type}) sent to user {user_id}")
        return notification

    @classmethod
    def for_user(cls, user_id, actor, status=None):
        if not cls._sees_everything(actor) and user_id != actor["user_id"]:
            cls._deny(actor, "You can only view your own notifications",
                      f"'{actor['username']}' tried to view the notifications of user {user_id}")
        query = Notification.query.filter_by(user_id=user_id)
        if status:
            query = query.filter_by(status=validate_enum(status, NOTIFICATION_STATUSES, "status"))
        return query.order_by(Notification.created_at.desc(), Notification.id.desc()).all()

    @classmethod
    def get_for(cls, notification_id, actor):
        notification = cls.get(notification_id)
        cls._check_owner(notification, actor, "view")
        return notification

    @classmethod
    def mark_read(cls, notification_id, actor):
        """Returns (notification, changed). Marking an already-read notification is not an error."""
        notification = cls.get(notification_id)
        if actor["role"] != ADMIN and notification.user_id != actor["user_id"]:
            cls._deny(actor, "You can only mark your own notifications as read",
                      f"'{actor['username']}' tried to mark notification {notification.id} as read")
        if notification.status == "Read":
            return notification, False
        notification.status = "Read"
        notification.read_at = utcnow()
        db.session.commit()
        log_event(actor["user_id"], "NOTIFICATION_READ", f"Notification {notification.id} marked as read")
        return notification, True

    @classmethod
    def search(cls, params, actor):
        reject_unknown_fields(params, cls.SEARCH_PARAMS)
        if not any(v.strip() for v in params.values()):
            raise ValidationError(f"Provide at least one search criterion: {', '.join(cls.SEARCH_PARAMS)}")

        query = Notification.query
        if params.get("user"):
            user = params["user"].strip()
            if not user.isdigit():
                raise ValidationError("'user' must be a user id")
            query = query.filter_by(user_id=int(user))
        if params.get("type"):
            query = query.filter_by(notification_type=validate_enum(params["type"], NOTIFICATION_TYPES, "type"))
        if params.get("severity"):
            query = query.filter_by(severity=validate_enum(params["severity"], SEVERITIES, "severity"))
        if params.get("status"):
            query = query.filter_by(status=validate_enum(params["status"], NOTIFICATION_STATUSES, "status"))
        if actor["role"] == ANALYST:          # analysts only ever search their own notifications
            query = query.filter_by(user_id=actor["user_id"])
        return query.order_by(Notification.created_at.desc(), Notification.id.desc()).all()

    @classmethod
    def delete(cls, notification_id, actor):
        notification = cls.get(notification_id)
        owner_id = notification.user_id      # read before the row is gone
        db.session.delete(notification)
        db.session.commit()
        log_event(actor["user_id"], "NOTIFICATION_DELETED",
                  f"Notification {notification_id} of user {owner_id} deleted", severity="Warning")
